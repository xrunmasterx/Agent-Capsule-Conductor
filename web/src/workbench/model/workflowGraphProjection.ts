export function canvasToWorkflowGraph(canvas: WorkspaceCanvasModel): WorkflowGraph {
  const executableEdges = runtimeCanvasEdges(canvas.edges);
  const boundaryEdges = workflowBoundaryEdges(canvas.edges);
  const focusBoundaryContext = workflowBoundaryContextForFocusCanvas(canvas);
  const runtimeWorkflows = canvas.workflows.filter((workflow) => !workflow.boundaryKind);
  const controlEdges = executableEdges
    .filter((edge): edge is Extract<WorkflowCanvasEdge, { kind: 'control' }> => edge.kind === 'control')
    .map((edge) => ({
      id: edge.id,
      from: edge.source.workflowId,
      to: edge.target.workflowId,
      label: 'control',
      condition: edge.condition || null,
      context: 'none',
      mapping: {},
    }));
  const dataEdges = executableEdges
    .filter((edge): edge is Extract<WorkflowCanvasEdge, { kind: 'data' }> => edge.kind === 'data')
    .map((edge) => ({
      id: edge.id,
      from: { node: edge.source.workflowId, port: edge.source.portId },
      to: { node: edge.target.workflowId, port: edge.target.portId },
      materialization: edge.materialization,
      required: true,
    }));
  return {
    id: canvas.id,
    version: '0.4.0',
    name: canvas.name,
    description: 'Graph-first workspace canvas generated by ACC Workbench.',
    nodes: runtimeWorkflows.map(workflowToGraphNode),
    edges: controlEdges,
    control_edges: controlEdges,
    data_edges: dataEdges,
    workspace_policy: {
      save_mode: 'local_binding',
      default_state_mode: 'stateful',
    },
    policy: { failure_mode: 'fail_fast', max_concurrency: DEFAULT_WORKFLOW_MAX_CONCURRENCY },
    metadata: {
      layout: canvas.layout || 'workspace-canvas',
      root_workflow_id: canvas.rootWorkflowId,
      directory_display_only: true,
      ...(canvas.layout === 'workflow-focus'
        ? {
            workflow_port_edges: boundaryEdges.map(canvasEdgeToGraphMetadataEdge),
          }
        : {}),
    },
    ...(canvas.layout === 'workflow-focus'
      ? {
          ...focusBoundaryPortsForGraph(canvas),
          workflow_input_bindings: workflowInputBindingsFromBoundaryEdges(focusBoundaryContext, boundaryEdges),
          workflow_output_bindings: workflowOutputBindingsFromBoundaryEdges(focusBoundaryContext, boundaryEdges),
        }
      : canvas.exposedOutputs || canvas.workflowOutputBindings
        ? {
            exposed_outputs: (canvas.exposedOutputs || []).map(portViewToGraphPort),
            workflow_output_bindings: canvas.workflowOutputBindings || [],
          }
        : {}),
  };
}

function focusBoundaryPortsForGraph(canvas: WorkspaceCanvasModel): Pick<
  WorkflowGraph,
  'exposed_inputs' | 'exposed_outputs'
> {
  const inputBoundary = canvas.workflows.find(
    (workflow) => workflow.boundaryKind === 'workflow_input',
  );
  const outputBoundary = canvas.workflows.find(
    (workflow) => workflow.boundaryKind === 'workflow_output',
  );
  return {
    exposed_inputs: (inputBoundary?.outputPorts || []).map((item) =>
      portViewToGraphPort(boundaryPort(item, 'input')),
    ),
    exposed_outputs: (outputBoundary?.inputPorts || []).map((item) =>
      portViewToGraphPort(boundaryPort(item, 'output')),
    ),
  };
}

export function graphForCurrentView(
  canvas: WorkspaceCanvasModel,
  focusedWorkflowId: string | null,
): WorkflowGraph {
  if (!focusedWorkflowId) {
    return canvasToWorkflowGraph(canvas);
  }
  const workflow = canvas.workflows.find((item) => item.id === focusedWorkflowId);
  if (!workflow) {
    return canvasToWorkflowGraph(canvas);
  }
  return internalWorkflowToGraph(workflow);
}

export function internalWorkflowToGraph(workflow: WorkflowContainerModel): WorkflowGraph {
  const executableEdges = runtimeCanvasEdges(workflow.internalEdges);
  const boundaryEdges = workflowBoundaryEdges(workflow.internalEdges);
  const boundaryContext = workflowBoundaryContextForContainer(workflow);
  const controlEdges = executableEdges
    .filter((edge): edge is Extract<WorkflowCanvasEdge, { kind: 'control' }> => edge.kind === 'control')
    .map((edge) => ({
      id: edge.id,
      from: edge.source.workflowId,
      to: edge.target.workflowId,
      label: 'control',
      condition: edge.condition || null,
      context: 'upstream_output',
      mapping: {},
    }));
  const dataEdges = executableEdges
    .filter((edge): edge is Extract<WorkflowCanvasEdge, { kind: 'data' }> => edge.kind === 'data')
    .map((edge) => ({
      id: edge.id,
      from: { node: edge.source.workflowId, port: edge.source.portId },
      to: { node: edge.target.workflowId, port: edge.target.portId },
      materialization: edge.materialization,
      required: true,
    }));
  return {
    id: workflow.id,
    version: '0.4.0',
    name: workflow.title,
    description: 'Workflow Focus Mode graph generated by ACC Workbench.',
    nodes: workflow.internalNodes.map(internalNodeToGraphNode),
    edges: controlEdges,
    control_edges: controlEdges,
    data_edges: dataEdges,
    exposed_inputs: workflow.inputPorts.map(portViewToGraphPort),
    exposed_outputs: workflow.outputPorts.map(portViewToGraphPort),
    workflow_input_bindings: workflowInputBindingsFromBoundaryEdges(boundaryContext, boundaryEdges),
    workflow_output_bindings: workflowOutputBindingsFromBoundaryEdges(boundaryContext, boundaryEdges),
    workspace_policy: {
      save_mode: 'local_binding',
      default_state_mode: 'stateful',
    },
    policy: { failure_mode: 'fail_fast', max_concurrency: DEFAULT_WORKFLOW_MAX_CONCURRENCY },
    metadata: {
      layout: 'workflow-focus',
      ...(workflow.bindingPath ? { binding_ref: workflow.bindingPath } : {}),
      workflow_port_edges: boundaryEdges.map(canvasEdgeToGraphMetadataEdge),
    },
  };
}

type BoundaryBindingNodeContext = {
  id: string;
  inputPorts: WorkflowPortView[];
  outputPorts: WorkflowPortView[];
};

type WorkflowBoundaryBindingContext = {
  id: string;
  inputPorts: WorkflowPortView[];
  outputPorts: WorkflowPortView[];
  nodes: BoundaryBindingNodeContext[];
};

function workflowBoundaryContextForContainer(workflow: WorkflowContainerModel): WorkflowBoundaryBindingContext {
  return {
    id: workflow.id,
    inputPorts: workflow.inputPorts,
    outputPorts: workflow.outputPorts,
    nodes: workflow.internalNodes.map((node) => ({
      id: node.id,
      inputPorts: internalNodeInputPorts(node),
      outputPorts: internalNodeOutputPorts(node),
    })),
  };
}

function workflowBoundaryContextForFocusCanvas(canvas: WorkspaceCanvasModel): WorkflowBoundaryBindingContext {
  const inputBoundary = canvas.workflows.find((workflow) => workflow.boundaryKind === 'workflow_input');
  const outputBoundary = canvas.workflows.find((workflow) => workflow.boundaryKind === 'workflow_output');
  return {
    id: canvas.id,
    inputPorts: inputBoundary?.outputPorts || [port('main', 'input', 'input')],
    outputPorts: outputBoundary?.inputPorts || [port('main', 'output', 'output')],
    nodes: canvas.workflows
      .filter((workflow) => !workflow.boundaryKind)
      .map((workflow) => ({
        id: workflow.id,
        inputPorts: workflow.inputPorts,
        outputPorts: workflowOutputPorts(workflow),
      })),
  };
}

function workflowInputBindingsFromBoundaryEdges(
  context: WorkflowBoundaryBindingContext,
  edges: WorkflowCanvasEdge[],
): NonNullable<WorkflowGraph['workflow_input_bindings']> {
  const inputBoundaryId = workflowInputBoundaryId(context.id);
  const bindings: NonNullable<WorkflowGraph['workflow_input_bindings']> = [];
  const seen = new Set<string>();
  edges.forEach((edge) => {
    if (edge.kind === 'data' && edge.source.workflowId === inputBoundaryId) {
      const sourcePort = edge.source.portId || 'main';
      const targetPort = edge.target.portId || 'main';
      const key = `${sourcePort}->${edge.target.workflowId}.${targetPort}`;
      if (seen.has(key)) {
        return;
      }
      seen.add(key);
      bindings.push({
        source_port: sourcePort,
        target: { node: edge.target.workflowId, port: targetPort },
        materialization: edge.materialization || 'copy',
        required: false,
      });
      return;
    }
    if (edge.kind !== 'control' || !isWorkflowInputBoundaryControlBinding(context.id, edge)) {
      return;
    }
    const targetNode = context.nodes.find((node) => node.id === edge.target.workflowId);
    const pairs = boundaryTransferPairs(edge).length
      ? boundaryTransferPairs(edge)
      : inferBoundaryPortPairs(context.inputPorts, targetNode?.inputPorts || [port('main', 'input', 'input')]);
    pairs.forEach(({ sourcePort, targetPort }) => {
      const targetAlreadyBound = bindings.some(
        (binding) => binding.target.node === edge.target.workflowId && binding.target.port === targetPort,
      );
      const key = `${sourcePort}->${edge.target.workflowId}.${targetPort}`;
      if (targetAlreadyBound || seen.has(key)) {
        return;
      }
      seen.add(key);
      bindings.push({
        source_port: sourcePort,
        target: { node: edge.target.workflowId, port: targetPort },
        materialization: edge.boundaryTransfer?.materialization || 'copy',
        required: false,
      });
    });
  });
  return bindings;
}

function workflowOutputBindingsFromBoundaryEdges(
  context: WorkflowBoundaryBindingContext,
  edges: WorkflowCanvasEdge[],
): NonNullable<WorkflowGraph['workflow_output_bindings']> {
  const outputBoundaryId = workflowOutputBoundaryId(context.id);
  const bindings: NonNullable<WorkflowGraph['workflow_output_bindings']> = [];
  const seen = new Set<string>();
  edges.forEach((edge) => {
    if (edge.kind === 'data' && edge.target.workflowId === outputBoundaryId) {
      const sourcePort = edge.source.portId || 'main';
      const targetPort = edge.target.portId || 'main';
      const key = `${edge.source.workflowId}.${sourcePort}->${targetPort}`;
      if (seen.has(key)) {
        return;
      }
      seen.add(key);
      bindings.push({
        source: { node: edge.source.workflowId, port: sourcePort },
        target_port: targetPort,
        materialization: edge.materialization || 'copy',
        required: true,
      });
      return;
    }
    if (edge.kind !== 'control' || !isWorkflowOutputBoundaryControlBinding(context.id, edge)) {
      return;
    }
    const sourceNode = context.nodes.find((node) => node.id === edge.source.workflowId);
    const pairs = boundaryTransferPairs(edge).length
      ? boundaryTransferPairs(edge)
      : inferBoundaryPortPairs(sourceNode?.outputPorts || [port('main', 'output', 'output')], context.outputPorts);
    pairs.forEach(({ sourcePort, targetPort }) => {
      const sourceAlreadyBound = bindings.some(
        (binding) => binding.source.node === edge.source.workflowId && binding.source.port === sourcePort,
      );
      const key = `${edge.source.workflowId}.${sourcePort}->${targetPort}`;
      if (sourceAlreadyBound || seen.has(key)) {
        return;
      }
      seen.add(key);
      bindings.push({
        source: { node: edge.source.workflowId, port: sourcePort },
        target_port: targetPort,
        materialization: edge.boundaryTransfer?.materialization || 'copy',
        required: true,
      });
    });
  });
  return bindings;
}

function boundaryTransferPairs(edge: WorkflowCanvasEdge): BoundaryTransferMapping[] {
  if (edge.kind !== 'control') {
    return [];
  }
  return edge.boundaryTransfer?.mappings || [];
}

function inferBoundaryPortPairs(
  sourcePorts: WorkflowPortView[],
  targetPorts: WorkflowPortView[],
): BoundaryTransferMapping[] {
  const sourceIds = uniquePortIds(sourcePorts);
  const targetIds = uniquePortIds(targetPorts);
  const sameName = sourceIds.filter((portId) => targetIds.includes(portId));
  const specific = sameName.filter((portId) => portId !== 'main');
  if (specific.length > 0) {
    return specific.map((portId) => ({ sourcePort: portId, targetPort: portId }));
  }
  if (sameName.includes('main')) {
    return [{ sourcePort: 'main', targetPort: 'main' }];
  }
  if (sourceIds.length === 1 && targetIds.length === 1) {
    return [{ sourcePort: sourceIds[0], targetPort: targetIds[0] }];
  }
  return [];
}

function uniquePortIds(ports: WorkflowPortView[]): string[] {
  const ids = ports.map((portValue) => portValue.id || 'main');
  return [...new Set(ids.length > 0 ? ids : ['main'])];
}

export function internalNodeToGraphNode(node: InternalNodeView): WorkflowGraphNode {
  const callableId = node.callableId || 'fake-agent.generic';
  const codexMode = normalizedCodexExecutionMode(node.codexExecutionMode);
  const metadata = invocationMetadata(
    internalInvocationLabel(node),
    codexMode,
    node.emptyInputPolicy,
  );
  const invocationPolicy = codexInvocationPolicyForMode(codexMode);
  return {
    id: node.id,
    callable_ref: {
      kind: node.kind === 'Tool' ? 'tool_class' : 'agent_class',
      id: callableId,
    },
    kind: node.kind === 'Tool' ? 'tool' : 'agent_session',
    label: internalInvocationLabel(node),
    input: internalNodeInput(node),
    input_mapping: {},
    cwd_policy: 'inherit_environment',
    input_ports: (node.inputPorts || [port('main', 'input', 'input')]).map(portViewToGraphPort),
    output_ports: internalNodeOutputPorts(node).map(portViewToGraphPort),
    ...(nodeControlPayload(node.forwardMainOutputOnControl, node.control)
      ? { control: nodeControlPayload(node.forwardMainOutputOnControl, node.control) }
      : {}),
    ...(node.outputSchema ? { output_schema: node.outputSchema } : {}),
    position: node.position,
    metadata,
    ...(invocationPolicy ? { invocation_policy: invocationPolicy } : {}),
  };
}

function invocationMetadata(
  label: string,
  codexMode: CodexExecutionMode,
  emptyInputPolicy?: EmptyInputPolicy,
): Record<string, unknown> {
  return {
    ui_label: label,
    ...(codexMode !== 'default' ? { codex_execution_mode: codexMode } : {}),
    ...(emptyInputPolicy === 'block' ? { empty_input_policy: 'block' } : {}),
  };
}

function internalNodeInput(node: InternalNodeView): Record<string, unknown> {
  if (node.input && Object.keys(node.input).length > 0) {
    return node.callableId === 'file-source.local'
      ? { path: String(node.input.path || '') }
      : node.input;
  }
  if (node.callableId === 'file-source.local') {
    return { path: '' };
  }
  return { user_prompt: node.task || internalInvocationLabel(node) };
}

export function workflowInvocationPreview(workflow: WorkflowContainerModel): Record<string, unknown> {
  const input = workflow.sourceInput || {};
  const userPrompt = promptFromInvocationInput(input);
  const codexMode = normalizedCodexExecutionMode(workflow.codexExecutionMode);
  return {
    prompt_policy: userPrompt ? { user_prompt: userPrompt } : {},
    overrides: { static_input: staticInputFromInvocationInput(input) },
    input_bindings: workflow.sourceInputMapping || {},
    workflow_call_input_bindings: workflow.sourceKind === 'workflow' ? [] : undefined,
    workflow_call_output_bindings: workflow.sourceKind === 'workflow' ? [] : undefined,
    invocation_policy: codexInvocationPolicyForMode(codexMode),
    metadata: invocationMetadata(workflowInvocationLabel(workflow), codexMode, workflow.emptyInputPolicy),
  };
}

export function internalNodeInvocationPreview(node: InternalNodeView): Record<string, unknown> {
  const input = node.input || {};
  const userPrompt = promptFromInvocationInput(input) || node.task || '';
  const codexMode = normalizedCodexExecutionMode(node.codexExecutionMode);
  return {
    prompt_policy: userPrompt ? { user_prompt: userPrompt } : {},
    overrides: { static_input: staticInputFromInvocationInput(input) },
    input_bindings: {},
    invocation_policy: codexInvocationPolicyForMode(codexMode),
    metadata: invocationMetadata(internalInvocationLabel(node), codexMode, node.emptyInputPolicy),
  };
}

function workflowToGraphNode(workflow: WorkflowContainerModel): WorkflowGraphNode {
  if (workflow.sourceKind && workflow.sourceKind !== 'workflow') {
    const callableId =
      workflow.callableId || workflow.internalNodes[0]?.callableId || 'fake-agent.generic';
    const callableKind = workflow.sourceKind === 'tool' ? 'tool_class' : 'agent_class';
    const codexMode = normalizedCodexExecutionMode(workflow.codexExecutionMode);
    const invocationPolicy = codexInvocationPolicyForMode(codexMode);
    return {
      id: workflow.id,
      callable_ref: {
        kind: callableKind,
        id: callableId,
      },
      kind: workflow.sourceKind,
      label: workflowInvocationLabel(workflow),
      input: workflow.sourceInput || (workflow.internalNodes[0] ? internalNodeInput(workflow.internalNodes[0]) : {}),
      input_mapping: workflow.sourceInputMapping || {},
      cwd_policy: workflow.relativeCwd ? 'relative_subdir' : 'inherit_environment',
      relative_cwd: workflow.relativeCwd,
      input_ports: workflow.inputPorts.map(portViewToGraphPort),
      output_ports: workflowOutputPorts(workflow).map(portViewToGraphPort),
      ...(nodeControlPayload(workflow.forwardMainOutputOnControl, workflow.control)
        ? { control: nodeControlPayload(workflow.forwardMainOutputOnControl, workflow.control) }
        : {}),
      ...(workflow.outputSchema ? { output_schema: workflow.outputSchema } : {}),
      position: workflow.position,
      metadata: invocationMetadata(
        workflowInvocationLabel(workflow),
        codexMode,
        workflow.emptyInputPolicy,
      ),
      ...(invocationPolicy ? { invocation_policy: invocationPolicy } : {}),
    };
  }
  if (!isInlineWorkflowContainer(workflow)) {
    const workflowRef = workflow.workflowRef || workflow.callableId || workflow.id;
    return {
      id: workflow.id,
      callable_ref: {
        kind: 'workflow_function',
        id: workflowRef,
      },
      kind: 'workflow',
      workflow_ref: workflowRef,
      label: workflowInvocationLabel(workflow),
      input: workflow.sourceInput || {},
      input_mapping: workflow.sourceInputMapping || {},
      cwd_policy: workflow.relativeCwd ? 'relative_subdir' : 'inherit_environment',
      relative_cwd: workflow.relativeCwd,
      input_ports: workflow.inputPorts.map(portViewToGraphPort),
      output_ports: workflow.outputPorts.map(portViewToGraphPort),
      ...(nodeControlPayload(workflow.forwardMainOutputOnControl, workflow.control)
        ? { control: nodeControlPayload(workflow.forwardMainOutputOnControl, workflow.control) }
        : {}),
      ...(workflow.outputSchema ? { output_schema: workflow.outputSchema } : {}),
      position: workflow.position,
      metadata: { ui_label: workflowInvocationLabel(workflow) },
    };
  }
  return {
    id: workflow.id,
    callable_ref: {
      kind: 'workflow_function',
      id: workflow.id,
    },
    kind: 'workflow',
    label: workflowInvocationLabel(workflow),
    input: { topic: `${workflow.title} workflow container` },
    input_mapping: {},
    cwd_policy: workflow.relativeCwd ? 'relative_subdir' : 'inherit_environment',
    relative_cwd: workflow.relativeCwd,
    input_ports: workflow.inputPorts.map(portViewToGraphPort),
    output_ports: workflow.outputPorts.map(portViewToGraphPort),
    ...(nodeControlPayload(workflow.forwardMainOutputOnControl, workflow.control)
      ? { control: nodeControlPayload(workflow.forwardMainOutputOnControl, workflow.control) }
      : {}),
    ...(workflow.outputSchema ? { output_schema: workflow.outputSchema } : {}),
    position: workflow.position,
    metadata: { ui_label: workflowInvocationLabel(workflow) },
    ui: {
      semantic_kind: 'workflow_container',
      ...(workflow.bindingPath ? { binding_ref: workflow.bindingPath } : {}),
      internal_nodes: workflow.internalNodes.map((node) => ({
        ...node,
        inputPorts: internalNodeInputPorts(node),
        outputPorts: internalNodeOutputPorts(node),
      })),
      internal_edges: workflow.internalEdges.map(canvasEdgeToGraphMetadataEdge),
    },
  };
}

function codexInvocationPolicyForMode(
  mode: CodexExecutionMode,
): WorkflowGraphNode['invocation_policy'] | undefined {
  if (mode === 'local_readonly_no_sandbox') {
    return {
      permission_profile: {
        workspace_access: 'read_only',
        network: false,
        shell: true,
        dangerous: true,
      },
    };
  }
  if (mode === 'danger_full_access') {
    return {
      permission_profile: {
        workspace_access: 'writes_workspace',
        network: true,
        shell: true,
        dangerous: true,
      },
    };
  }
  return undefined;
}

function nodeControlPayload(
  value: boolean | null | undefined,
  existing?: WorkflowGraphNode['control'],
): WorkflowGraphNode['control'] | undefined {
  const payload = existing ? { ...existing } : {};
  if (typeof value === 'boolean') {
    payload.forward_main_output_on_control = value;
  }
  return Object.keys(payload).length > 0 ? payload : undefined;
}

export function port(
  id: string,
  label: string,
  direction: PortDirection,
  required = false,
  cardinality = 'one',
): WorkflowPortView {
  return { id, label, direction, required, cardinality, artifactTypes: ['artifact'] };
}

export function internalNodeInputPorts(node: InternalNodeView): WorkflowPortView[] {
  return node.inputPorts || [port('main', 'input', 'input')];
}

export function internalNodeOutputPorts(node: InternalNodeView): WorkflowPortView[] {
  return effectiveOutputPortsForNode({
    outputSchema: node.outputSchema,
    outputPorts: node.outputPorts || [port('main', 'output', 'output')],
  });
}

export function workflowOutputPorts(workflow: WorkflowContainerModel): WorkflowPortView[] {
  if (workflow.sourceKind && workflow.sourceKind !== 'workflow') {
    return outputPortsFromSchema(workflow.outputSchema, workflow.outputPorts);
  }
  return workflow.outputPorts;
}

export function workflowOutputPortsReadonly(workflow: WorkflowContainerModel): boolean {
  return Boolean(workflow.sourceKind && workflow.sourceKind !== 'workflow');
}

export function canvasEdgeToGraphMetadataEdge(edge: WorkflowCanvasEdge): WorkflowDataEdge | WorkflowGraphEdge {
  if (edge.kind === 'data') {
    return {
      id: edge.id,
      from: { node: edge.source.workflowId, port: edge.source.portId },
      to: { node: edge.target.workflowId, port: edge.target.portId },
      materialization: edge.materialization,
      required: workflowBoundaryKind(edge.source.workflowId) === 'workflow_input' ? false : true,
    };
  }
  return {
    id: edge.id,
    from: edge.source.workflowId,
    to: edge.target.workflowId,
    label: 'control',
    condition: edge.condition || null,
    context: 'none',
    mapping: {},
    ...(edge.boundaryTransfer ? { boundary_transfer: boundaryTransferToGraphMetadata(edge.boundaryTransfer) } : {}),
  };
}

export function edgeCanonicalPreview(edge: WorkflowCanvasEdge, canvas?: WorkspaceCanvasModel): Record<string, unknown> {
  if (edge.kind === 'data') {
    const hasControlDependency = canvas
      ? allCanvasEdges(canvas).some(
          (candidate) =>
            candidate.kind === 'control' &&
            candidate.source.workflowId === edge.source.workflowId &&
            candidate.target.workflowId === edge.target.workflowId,
        )
      : false;
    return {
      data_edge: {
        source: { node: edge.source.workflowId, port: edge.source.portId || 'main' },
        target: { node: edge.target.workflowId, port: edge.target.portId || 'main' },
        materialization: edge.materialization,
      },
      auto_added_control_edge: !isWorkflowBoundaryEdge(edge) && !hasControlDependency,
    };
  }
  const boundaryWorkflowId = workflowIdForBoundaryMainBinding(edge);
  if (boundaryWorkflowId && isWorkflowInputBoundaryControlBinding(boundaryWorkflowId, edge)) {
    const context = canvas ? workflowBoundaryContextForEdge(canvas, boundaryWorkflowId) : null;
    const bindings = context ? workflowInputBindingsFromBoundaryEdges(context, [edge]) : [];
    return {
      workflow_input_bindings: bindings,
      workbench_projection: 'boundary_control_port_binding',
      runtime_control_edge: false,
    };
  }
  if (boundaryWorkflowId && isWorkflowOutputBoundaryControlBinding(boundaryWorkflowId, edge)) {
    const context = canvas ? workflowBoundaryContextForEdge(canvas, boundaryWorkflowId) : null;
    const bindings = context ? workflowOutputBindingsFromBoundaryEdges(context, [edge]) : [];
    return {
      workflow_output_bindings: bindings,
      workbench_projection: 'boundary_control_port_binding',
      runtime_control_edge: false,
    };
  }
  return {
    control_edge: {
      from: edge.source.workflowId,
      to: edge.target.workflowId,
      context: 'none',
    },
  };
}

function workflowBoundaryContextForEdge(
  canvas: WorkspaceCanvasModel,
  workflowId: string,
): WorkflowBoundaryBindingContext | null {
  if (canvas.layout === 'workflow-focus' && canvas.id === workflowId) {
    return workflowBoundaryContextForFocusCanvas(canvas);
  }
  const workflow = canvas.workflows.find((item) => item.id === workflowId);
  return workflow ? workflowBoundaryContextForContainer(workflow) : null;
}

function allCanvasEdges(canvas: WorkspaceCanvasModel): WorkflowCanvasEdge[] {
  return [...canvas.edges, ...canvas.workflows.flatMap((workflow) => workflow.internalEdges)];
}

function portViewToGraphPort(portView: WorkflowPortView): WorkflowPort {
  return {
    id: portView.id,
    direction: portView.direction,
    required: portView.required,
    cardinality: portView.cardinality || 'one',
    artifact_types: portView.artifactTypes || ['artifact'],
  };
}

function runtimeCanvasEdges(edges: WorkflowCanvasEdge[]): WorkflowCanvasEdge[] {
  return edges.filter((edge) => !isWorkflowBoundaryEdge(edge));
}

function workflowBoundaryEdges(edges: WorkflowCanvasEdge[]): WorkflowCanvasEdge[] {
  return edges.filter(isWorkflowBoundaryEdge);
}

function isWorkflowShellNode(workflow: WorkflowContainerModel): boolean {
  return !workflow.boundaryKind && (workflow.sourceKind || 'workflow') === 'workflow';
}

export function isInlineWorkflowContainer(workflow: WorkflowContainerModel): boolean {
  if (!isWorkflowShellNode(workflow)) {
    return false;
  }
  if (workflow.workflowBodyKind) {
    return workflow.workflowBodyKind === 'inline_container';
  }
  return !workflow.workflowRef || workflow.internalNodes.length > 0 || workflow.internalEdges.length > 0;
}

export function boundaryPort(portValue: WorkflowPortView, direction: PortDirection): WorkflowPortView {
  return {
    ...portValue,
    direction,
    label: portValue.label || portValue.id,
  };
}
